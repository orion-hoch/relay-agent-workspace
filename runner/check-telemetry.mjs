import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
import { cpuPercent, gpuPercent, createHostSampler } from './host-telemetry.mjs';

assert.equal(cpuPercent(null, { idle: 50, total: 100 }), null);
assert.equal(cpuPercent({ idle: 50, total: 100 }, { idle: 75, total: 200 }), 75);
assert.equal(cpuPercent({ idle: 50, total: 100 }, { idle: 50, total: 100 }), null);
assert.equal(gpuPercent('0\n'), 0);
assert.equal(gpuPercent('3\n12\n'), 12);
assert.equal(gpuPercent('[N/A]\n'), null);
assert.equal(gpuPercent(''), null);
const require = createRequire(import.meta.url);
const ts = require('typescript');
const source = await readFile(new URL('../lib/buzz/telemetry.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } });
const helpers = {};
new Function('exports', compiled.outputText)(helpers);
const now = Date.now();
const metrics = { cpuPercent: null, gpuPercent: 0, ramUsedBytes: 20, ramTotalBytes: 100, measuredAt: new Date(now).toISOString() };
assert.equal(helpers.validMetrics(metrics), true);
assert.equal(helpers.validMetrics({ ...metrics, ramUsedBytes: 101 }), false);
assert.equal(helpers.validMetrics({ ...metrics, gpuPercent: undefined }), false);
assert.deepEqual(helpers.freshMetrics({ receivedAt: metrics.measuredAt, metrics }, now), metrics);
assert.equal(helpers.freshMetrics({ receivedAt: metrics.measuredAt, metrics }, now + 30001), null);
assert.equal(helpers.freshMetrics({ receivedAt: metrics.measuredAt, metrics: { ...metrics, measuredAt: new Date(now + 6000).toISOString() } }, now), null);
const sample = createHostSampler();
await sample();
await new Promise(resolve => setTimeout(resolve, 250));
const observed = await sample();
assert.equal(helpers.validMetrics(observed), true);
console.log(JSON.stringify({ result: 'Telemetry parsing and stale/unknown readings verified', observed }));
